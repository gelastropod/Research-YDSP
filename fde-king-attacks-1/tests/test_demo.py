import unittest
import numpy as np
from Crypto.Cipher import AES
from Crypto.Util.strxor import strxor
from demo.modes import keys,make_mask,ghash,transform,NAMES,MASKS,SECTOR0
from demo.raster import changes,versions

class Controls(unittest.TestCase):
    def test_three_regions_and_byte_layout(self):
        v=versions()
        self.assertEqual(np.flatnonzero(changes(v["base"],v["edited"])).tolist(),[89,133,134,136,137,149,150,151,152,153,166,167,168,183,234])
        # The actual texture decoder must place a changed BC3 record at its expected coordinates.
        from demo.raster import image
        base=v["base"]
        donor=v["edited"][89*16:90*16]
        for j in range(256):
            replacement=donor if donor!=base[j*16:j*16+16] else base[:16]
            changed=base[:16*j]+replacement+base[16*j+16:]
            yy,xx=np.where(np.any(image(changed)!=image(base),axis=2))
            self.assertGreater(len(yy),0)
            self.assertTrue(np.all((yy//4)*16+xx//4==j))
    def test_different_implementations_of_xts_agree(self):
        # Independent full-block XTS reference, including the alpha reduction and sector restart.
        k=keys("xts-control"); a=AES.new(k["xts/data"],AES.MODE_ECB);b=AES.new(k["xts/tweak"],AES.MODE_ECB)
        p=versions()["base"];out=bytearray()
        for off in range(0,len(p),512):
            t=int.from_bytes(b.encrypt((SECTOR0+off//512).to_bytes(16,"little")),"little")
            for i in range(off,off+512,16):
                mask=t.to_bytes(16,"little")
                out.extend(strxor(mask,a.encrypt(strxor(p[i:i+16],mask))))
                t=((t<<1)&((1<<128)-1))^(0x87 if t>>127 else 0)
        self.assertEqual(bytes(out),transform("XTS",p,512,k))
    def test_ghash_matches_gcm_authentication_step(self):
        # Recover the pure GHASH from a library GCM tag for the same ciphertext.
        # GCM authenticates C plus its length; here AAD is empty.
        key=bytes(range(32)); iv=bytes(range(12)); aes=AES.new(key,AES.MODE_ECB)
        c,tag=AES.new(key,AES.MODE_GCM,nonce=iv).encrypt_and_digest(bytes(range(48)))
        expected=strxor(tag,aes.encrypt(iv+b"\x00\x00\x00\x01"))
        self.assertEqual(ghash(aes.encrypt(bytes(16)),c),expected)
    def test_mask_vectors(self):
        # Fixed outputs independently generated by the OpenSSL 'mac' CLI.
        refs={"CMAC":"068f7b24ca92101adca96c9c3578eea3","KMAC128":"3de93e533032e131b8cdc282aa1f98f0",
              "BLAKE2s":"b23398f910599f3c09b6549fa81bcb46","HMAC-SHA256":"c31a7fb7648a830a8104434cd9cc3fda"}
        for name,expected in refs.items():
            self.assertEqual(make_mask(name,bytes(range(32)))(bytes(range(48))).hex(),expected)
        self.assertEqual(make_mask("BLAKE3",b"whats the Elvish word for friend")(b"").hex(),"92b2b75604ed3c761f9d6f62392c8a92")
    def test_first_and_last_block_on_sector_boundaries(self):
        k=keys("boundary fixture");p=bytes(1024);q=bytearray(p);q[511]=9;q[512]=8
        for name in NAMES:
            with self.subTest(name=name):
                a,b=(transform(name,x,512,k) for x in (p,bytes(q)))
                changed=changes(a,b)
                self.assertFalse(changed[:31].any());self.assertTrue(changed[31]);self.assertTrue(changed[32])
                self.assertEqual(transform(name,b,512,k,decrypt=True),q)
                if name in ("XTS","ECB"):self.assertFalse(changed[33:].any())
if __name__=="__main__": unittest.main()
